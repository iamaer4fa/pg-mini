#[derive(Debug, Clone)]
pub struct EditableCell {
    pub text: String,
    pub is_null: bool,
    pub use_default: bool,
}

impl EditableCell {
    pub fn from_cell(cell: &CellValue) -> Self {
        Self {
            text: cell.text.clone(),
            is_null: cell.is_null,
            use_default: false,
        }
    }
}

impl CellValue {
    pub fn new_null() -> Self {
        Self {
            text: "NULL".to_string(),
            is_null: true,
            is_number: false,
        }
    }

    pub fn new_text(text: impl Into<String>) -> Self {
        Self {
            text: text.into(),
            is_null: false,
            is_number: false,
        }
    }

    pub fn new_number(text: impl Into<String>) -> Self {
        Self {
            text: text.into(),
            is_null: false,
            is_number: true,
        }
    }
}

