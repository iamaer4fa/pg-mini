#[derive(Debug, Clone)]
pub struct DbObjectRef {
    pub kind: DbObjectKind,
    pub schema: Option<String>,
    pub name: String,
    pub identity_arguments: Option<String>,
}

impl DbObjectRef {
    pub fn qualified_name(&self) -> String {
        let mut name = qualified_name(self.schema.as_deref(), &self.name);
        if matches!(self.kind, DbObjectKind::Function | DbObjectKind::Procedure) {
            name.push('(');
            name.push_str(self.identity_arguments.as_deref().unwrap_or(""));
            name.push(')');
        }
        name
    }

    pub fn drop_sql(&self) -> String {
        let command = match self.kind {
            DbObjectKind::Database => "DATABASE",
            DbObjectKind::Schema => "SCHEMA",
            DbObjectKind::Table => "TABLE",
            DbObjectKind::View => "VIEW",
            DbObjectKind::MaterializedView => "MATERIALIZED VIEW",
            DbObjectKind::Sequence => "SEQUENCE",
            DbObjectKind::Function => "FUNCTION",
            DbObjectKind::Procedure => "PROCEDURE",
            DbObjectKind::Type => "TYPE",
            DbObjectKind::Extension => "EXTENSION",
        };
        format!("DROP {command} {};", self.qualified_name())
    }

    pub fn rename_sql(&self, new_name: &str) -> Option<String> {
        let command = match self.kind {
            DbObjectKind::Database => "DATABASE",
            DbObjectKind::Schema => "SCHEMA",
            DbObjectKind::Table => "TABLE",
            DbObjectKind::View => "VIEW",
            DbObjectKind::MaterializedView => "MATERIALIZED VIEW",
            DbObjectKind::Sequence => "SEQUENCE",
            DbObjectKind::Function => "FUNCTION",
            DbObjectKind::Procedure => "PROCEDURE",
            DbObjectKind::Type => "TYPE",
            DbObjectKind::Extension => return None,
        };
        let target = if matches!(self.kind, DbObjectKind::Database | DbObjectKind::Schema) {
            quote_ident(&self.name)
        } else {
            self.qualified_name()
        };
        Some(format!(
            "ALTER {command} {target} RENAME TO {};",
            quote_ident(new_name)
        ))
    }

    pub fn properties_sql(&self) -> String {
        match self.kind {
            DbObjectKind::Database => format!(
                "SELECT datname AS database_name, pg_catalog.pg_get_userbyid(datdba) AS owner,\n\
                 pg_catalog.pg_size_pretty(pg_catalog.pg_database_size(datname)) AS size\n\
                 FROM pg_catalog.pg_database WHERE datname = {};",
                quote_literal(&self.name)
            ),
            DbObjectKind::Schema => format!(
                "SELECT n.nspname AS schema_name, pg_get_userbyid(n.nspowner) AS owner\n\
                 FROM pg_catalog.pg_namespace AS n WHERE n.nspname = {};",
                quote_literal(self.name.as_str())
            ),
            DbObjectKind::Table | DbObjectKind::View | DbObjectKind::MaterializedView => format!(
                "SELECT a.attname AS column_name, pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,\n\
                 a.attnotnull AS not_null, pg_catalog.pg_get_expr(d.adbin, d.adrelid) AS default_value\n\
                 FROM pg_catalog.pg_attribute AS a\n\
                 JOIN pg_catalog.pg_class AS c ON c.oid = a.attrelid\n\
                 JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace\n\
                 LEFT JOIN pg_catalog.pg_attrdef AS d ON d.adrelid = c.oid AND d.adnum = a.attnum\n\
                 WHERE n.nspname = {} AND c.relname = {} AND a.attnum > 0 AND NOT a.attisdropped\n\
                 ORDER BY a.attnum;",
                quote_literal(self.schema.as_deref().unwrap_or("")),
                quote_literal(&self.name)
            ),
            DbObjectKind::Function | DbObjectKind::Procedure => format!(
                "SELECT pg_catalog.pg_get_functiondef({}::pg_catalog.regprocedure) AS definition;",
                quote_literal(&self.qualified_name())
            ),
            DbObjectKind::Sequence => format!("SELECT * FROM {};", self.qualified_name()),
            DbObjectKind::Type => format!(
                "SELECT t.typname AS type_name, t.typtype AS type_kind, pg_catalog.format_type(t.typbasetype, t.typtypmod) AS base_type\n\
                 FROM pg_catalog.pg_type AS t JOIN pg_catalog.pg_namespace AS n ON n.oid = t.typnamespace\n\
                 WHERE n.nspname = {} AND t.typname = {};",
                quote_literal(self.schema.as_deref().unwrap_or("")),
                quote_literal(&self.name)
            ),
            DbObjectKind::Extension => format!(
                "SELECT e.extname, e.extversion, n.nspname AS schema_name\n\
                 FROM pg_catalog.pg_extension AS e JOIN pg_catalog.pg_namespace AS n ON n.oid = e.extnamespace\n\
                 WHERE e.extname = {};",
                quote_literal(&self.name)
            ),
        }
    }

    pub fn generate_sql_query(&self) -> String {
        match self.kind {
            DbObjectKind::Database => format!(
                "SELECT format('CREATE DATABASE %I WITH OWNER = %I ENCODING = %L LC_COLLATE = %L LC_CTYPE = %L TEMPLATE = template0;',\n\
                 d.datname, pg_catalog.pg_get_userbyid(d.datdba), pg_catalog.pg_encoding_to_char(d.encoding),\n\
                 d.datcollate, d.datctype) AS create_sql\n\
                 FROM pg_catalog.pg_database AS d WHERE d.datname = {};",
                quote_literal(&self.name)
            ),
            DbObjectKind::Schema => format!(
                "SELECT format('CREATE SCHEMA %I AUTHORIZATION %I;', n.nspname,\n\
                 pg_catalog.pg_get_userbyid(n.nspowner)) AS create_sql\n\
                 FROM pg_catalog.pg_namespace AS n WHERE n.nspname = {};",
                quote_literal(&self.name)
            ),
            DbObjectKind::Table => {
                let schema = quote_literal(self.schema.as_deref().unwrap_or(""));
                let table = quote_literal(&self.name);
                format!(
                    "SELECT format('CREATE TABLE %I.%I (%s%s);', n.nspname, c.relname,\n\
                     string_agg(format('%I %s%s%s%s', a.attname,\n\
                     pg_catalog.format_type(a.atttypid, a.atttypmod),\n\
                     CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,\n\
                     CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,\n\
                     CASE WHEN d.adbin IS NULL THEN '' ELSE ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) END), ', ' ORDER BY a.attnum),\n\
                     COALESCE((SELECT ', ' || string_agg(pg_catalog.pg_get_constraintdef(con.oid, true), ', ' ORDER BY con.conname)\n\
                       FROM pg_catalog.pg_constraint AS con WHERE con.conrelid = c.oid), '')) AS create_sql\n\
                     FROM pg_catalog.pg_class AS c\n\
                     JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace\n\
                     JOIN pg_catalog.pg_attribute AS a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped\n\
                     LEFT JOIN pg_catalog.pg_attrdef AS d ON d.adrelid = c.oid AND d.adnum = a.attnum\n\
                     WHERE n.nspname = {schema} AND c.relname = {table}\n\
                     GROUP BY n.nspname, c.relname, c.oid;",
                    schema = schema,
                    table = table,
                )
            }
            DbObjectKind::View | DbObjectKind::MaterializedView => format!(
                "SELECT 'CREATE {} ' || pg_catalog.quote_ident(n.nspname) || '.' || pg_catalog.quote_ident(c.relname) ||\n\
                 ' AS ' || pg_catalog.pg_get_viewdef(c.oid, true) || ';' AS create_sql\n\
                 FROM pg_catalog.pg_class AS c JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace\n\
                 WHERE n.nspname = {} AND c.relname = {};",
                if self.kind == DbObjectKind::View {
                    "VIEW"
                } else {
                    "MATERIALIZED VIEW"
                },
                quote_literal(self.schema.as_deref().unwrap_or("")),
                quote_literal(&self.name)
            ),
            DbObjectKind::Function | DbObjectKind::Procedure => self.properties_sql(),
            DbObjectKind::Sequence => format!(
                "SELECT format('CREATE SEQUENCE %I.%I AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s CACHE %s%s;',\n\
                 n.nspname, c.relname, pg_catalog.format_type(s.seqtypid, NULL), s.seqincrement,\n\
                 s.seqmin, s.seqmax, s.seqstart, s.seqcache,\n\
                 CASE WHEN s.seqcycle THEN ' CYCLE' ELSE ' NO CYCLE' END) AS create_sql\n\
                 FROM pg_catalog.pg_sequence AS s\n\
                 JOIN pg_catalog.pg_class AS c ON c.oid = s.seqrelid\n\
                 JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace\n\
                 WHERE n.nspname = {} AND c.relname = {};",
                quote_literal(self.schema.as_deref().unwrap_or("")),
                quote_literal(&self.name)
            ),
            DbObjectKind::Type => format!(
                "SELECT CASE\n\
                 WHEN t.typtype = 'e' THEN format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,\n\
                   (SELECT string_agg(pg_catalog.quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)\n\
                    FROM pg_catalog.pg_enum AS e WHERE e.enumtypid = t.oid))\n\
                 WHEN t.typtype = 'd' THEN format('CREATE DOMAIN %I.%I AS %s%s;', n.nspname, t.typname,\n\
                   pg_catalog.format_type(t.typbasetype, t.typtypmod),\n\
                   CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END)\n\
                 ELSE format('-- DDL for type %I.%I requires additional type-specific options.', n.nspname, t.typname)\n\
                 END AS create_sql\n\
                 FROM pg_catalog.pg_type AS t\n\
                 JOIN pg_catalog.pg_namespace AS n ON n.oid = t.typnamespace\n\
                 WHERE n.nspname = {} AND t.typname = {};",
                quote_literal(self.schema.as_deref().unwrap_or("")),
                quote_literal(&self.name)
            ),
            DbObjectKind::Extension => format!(
                "SELECT format('CREATE EXTENSION %I WITH SCHEMA %I VERSION %L;',\n\
                 e.extname, n.nspname, e.extversion) AS create_sql\n\
                 FROM pg_catalog.pg_extension AS e\n\
                 JOIN pg_catalog.pg_namespace AS n ON n.oid = e.extnamespace\n\
                 WHERE e.extname = {};",
                quote_literal(&self.name)
            ),
        }
    }
}

fn qualified_name(schema: Option<&str>, name: &str) -> String {
    match schema {
        Some(schema) => format!("{}.{}", quote_ident(schema), quote_ident(name)),
        None => quote_ident(name),
    }
}

fn quote_ident(value: &str) -> String {
    format!("\"{}\"", value.replace('"', "\"\""))
}

fn quote_literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

