#[cfg(test)]
mod object_browser_tests {
    use super::{DbObjectKind, DbObjectRef};

    #[test]
    fn object_sql_quotes_identifiers_and_targets_overloads() {
        let table = DbObjectRef {
            kind: DbObjectKind::Table,
            schema: Some("odd\"schema".to_string()),
            name: "odd\"table".to_string(),
            identity_arguments: None,
        };
        assert_eq!(table.qualified_name(), "\"odd\"\"schema\".\"odd\"\"table\"");
        assert_eq!(
            table.drop_sql(),
            "DROP TABLE \"odd\"\"schema\".\"odd\"\"table\";"
        );
        assert_eq!(
            table.rename_sql("new\"table").as_deref(),
            Some("ALTER TABLE \"odd\"\"schema\".\"odd\"\"table\" RENAME TO \"new\"\"table\";")
        );

        let function = DbObjectRef {
            kind: DbObjectKind::Function,
            schema: Some("public".to_string()),
            name: "lookup".to_string(),
            identity_arguments: Some("integer, text".to_string()),
        };
        assert_eq!(
            function.drop_sql(),
            "DROP FUNCTION \"public\".\"lookup\"(integer, text);"
        );
    }

    #[test]
    fn extension_rename_is_not_generated() {
        let extension = DbObjectRef {
            kind: DbObjectKind::Extension,
            schema: None,
            name: "sample".to_string(),
            identity_arguments: None,
        };
        assert!(extension.rename_sql("renamed").is_none());
    }

    #[test]
    fn generated_table_definition_query_scopes_catalog_lookup() {
        let table = DbObjectRef {
            kind: DbObjectKind::Table,
            schema: Some("odd'schema".to_string()),
            name: "users".to_string(),
            identity_arguments: None,
        };
        let query = table.generate_sql_query();
        assert!(query.contains("n.nspname = 'odd''schema'"));
        assert!(query.contains("c.relname = 'users'"));
        assert!(query.contains("CREATE TABLE"));
    }
}
