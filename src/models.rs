#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum DbObjectKind {
    Database,
    Schema,
    Table,
    View,
    MaterializedView,
    Sequence,
    Function,
    Procedure,
    Type,
    Extension,
}

impl DbObjectKind {
    pub fn label(self) -> &'static str {
        match self {
            Self::Database => "Databases",
            Self::Schema => "Schemas",
            Self::Table => "Tables",
            Self::View => "Views",
            Self::MaterializedView => "Materialized Views",
            Self::Sequence => "Sequences",
            Self::Function => "Functions",
            Self::Procedure => "Procedures",
            Self::Type => "Types",
            Self::Extension => "Extensions",
        }
    }

    pub fn singular(self) -> &'static str {
        match self {
            Self::Database => "Database",
            Self::Schema => "Schema",
            Self::Table => "Table",
            Self::View => "View",
            Self::MaterializedView => "Materialized View",
            Self::Sequence => "Sequence",
            Self::Function => "Function",
            Self::Procedure => "Procedure",
            Self::Type => "Type",
            Self::Extension => "Extension",
        }
    }

    pub fn icon(self) -> &'static str {
        match self {
            Self::Database => "🗄️",
            Self::Schema => "📁",
            Self::Table => "📄",
            Self::View => "👁",
            Self::MaterializedView => "🧱",
            Self::Sequence => "🔢",
            Self::Function => "ƒ",
            Self::Procedure => "⚙",
            Self::Type => "🔤",
            Self::Extension => "🧩",
        }
    }

    pub fn create_sql(self, schema: Option<&str>, name: &str) -> String {
        let qualified = qualified_name(schema, name);
        match self {
            Self::Database => format!("CREATE DATABASE {};", quote_ident(name)),
            Self::Schema => format!("CREATE SCHEMA {};", quote_ident(name)),
            Self::Table => format!(
                "CREATE TABLE {} (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);",
                qualified
            ),
            Self::View => format!("CREATE VIEW {} AS\nSELECT 1 AS id;", qualified),
            Self::MaterializedView => {
                format!("CREATE MATERIALIZED VIEW {} AS\nSELECT 1 AS id;", qualified)
            }
            Self::Sequence => format!("CREATE SEQUENCE {};", qualified),
            Self::Function => format!(
                "CREATE FUNCTION {}() RETURNS void\nLANGUAGE plpgsql AS $$\nBEGIN\n    RETURN;\nEND;\n$$;",
                qualified
            ),
            Self::Procedure => format!(
                "CREATE PROCEDURE {}()\nLANGUAGE plpgsql AS $$\nBEGIN\n    NULL;\nEND;\n$$;",
                qualified
            ),
            Self::Type => format!("CREATE TYPE {} AS ENUM ('value');", qualified),
            Self::Extension => format!("CREATE EXTENSION {};", quote_ident(name)),
        }
    }
}

